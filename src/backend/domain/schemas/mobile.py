import datetime
from typing import List, Optional
from pydantic import BaseModel, Field, ConfigDict


class MobileTransactionPayload(BaseModel):
    """Payload representing a single transaction registered on the mobile device."""
    model_config = ConfigDict(from_attributes=True)

    event_id: str = Field(..., description="UUIDv4 identifier generated by the mobile client for idempotency")
    scope: str = Field(default="PERSONAL", description="Transaction scope ('PERSONAL' or future 'JOINT')")
    amount: float = Field(..., gt=0, description="Transaction amount in EUR (strictly positive)")
    description: str = Field(..., min_length=1, max_length=200, description="Concept / note of the transaction")
    date: datetime.date = Field(..., description="Accounting date (YYYY-MM-DD)")
    subcategory_id: int = Field(..., description="Target subcategory ID")
    subcategory_name: Optional[str] = Field(default=None, description="Descriptive name of the subcategory for fallback matching")
    created_at_utc: Optional[str] = Field(default=None, description="ISO 8601 UTC timestamp of creation on the device")


class MobileSyncRequest(BaseModel):
    """Batch of mobile transactions to synchronize with the backend."""
    device_id: str = Field(default="mobile-device", description="Identifier of the emitting mobile client")
    transactions: List[MobileTransactionPayload] = Field(default_factory=list, description="Pending mobile transactions")


class MobileSyncResponse(BaseModel):
    """Result of processing a mobile sync batch."""
    success: bool = True
    processed_count: int = Field(0, description="Number of newly inserted transactions")
    ignored_duplicates_count: int = Field(0, description="Number of duplicate transactions skipped")
    server_timestamp_utc: str = Field(..., description="Server timestamp when the batch was processed")


class MobileCatalogSubcategory(BaseModel):
    """Subcategory item for mobile display and offline selection."""
    model_config = ConfigDict(from_attributes=True)

    id: int
    name: str
    category_id: int
    category_name: str
    is_frequent: bool = False


class MobileCatalogResponse(BaseModel):
    """Full catalog data necessary for mobile offline operation."""
    device_id: str
    last_updated_utc: str
    personal_subcategories: List[MobileCatalogSubcategory]
    frequent_concepts: List[str] = Field(default_factory=list)


class MobileSyncStatusResponse(BaseModel):
    """Status and health metrics for mobile synchronization."""
    server_online: bool = True
    server_time_utc: str
    today_transactions_count: int
    pending_inbox_files: int = 0
